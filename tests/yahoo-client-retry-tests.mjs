import assert from 'node:assert/strict';
import {createYahooClient} from '../src/data/yahoo-client.js';
const response=(status,body='upstream unavailable')=>({ok:status===200,status,json:async()=>({ok:true}),text:async()=>body});
let attempts=0,delays=[];
const get=createYahooClient({accessToken:'test-token',retryDelayMs:10,sleep:async ms=>delays.push(ms),fetchImpl:async()=>{attempts++;return response(attempts<3?503:200)}});
assert.deepEqual(await get('league/test'),{ok:true});
assert.equal(attempts,3);
assert.deepEqual(delays,[10,20]);
attempts=0;
const fail=createYahooClient({accessToken:'test-token',retryDelayMs:0,sleep:async()=>{},fetchImpl:async()=>{attempts++;return response(503)}});
await assert.rejects(()=>fail('league/test'),/503.*3 attempt/);
assert.equal(attempts,3);
attempts=0;
const unauthorized=createYahooClient({accessToken:'test-token',fetchImpl:async()=>{attempts++;return response(401)}});
await assert.rejects(()=>unauthorized('league/test'),/401.*1 attempt/);
assert.equal(attempts,1);
attempts=0;
const network=createYahooClient({accessToken:'test-token',retryDelayMs:0,sleep:async()=>{},fetchImpl:async()=>{attempts++;if(attempts===1)throw new TypeError('fetch failed');return response(200)}});
assert.deepEqual(await network('league/test'),{ok:true});
assert.equal(attempts,2);
assert.throws(()=>createYahooClient({accessToken:'test-token',maxRetries:9}),/maxRetries/);
console.log('yahoo-client-retry-tests: all checks passed');
