import assert from 'node:assert/strict';
import {eligibleForSlot,matchingProjectionRows,unavailableStatus} from '../src/model/future-candidate-evidence.js';
import {inventoryFutureRosterCandidates} from '../src/model/future-roster-candidate-inventory.js';
import {diagnoseFutureReplacementExclusions} from '../src/model/future-replacement-level.js';
const candidate={id:'yahoo-7',name:'Example Player Jr.',position:'WR',nflTeam:'JAC',byeWeek:8,status:'ACTIVE'};
const projection={season:2026,week:11,name:'Example Player',position:'WR',nflTeam:'JAX',projection:8};
const gaps=[{teamName:'Team',week:11,slots:[{slot:'W/R/T'}]}];
assert.equal(eligibleForSlot(candidate,'W/R/T'),true);
assert.equal(eligibleForSlot({position:'D/ST'},'DST'),true);
assert.equal(unavailableStatus('BYE'),true);
assert.equal(matchingProjectionRows(candidate,[projection],11,{season:2026}).length,1);
assert.equal(matchingProjectionRows(candidate,[projection],11,{season:2025}).length,0);
assert.equal(matchingProjectionRows(candidate,[projection,{...projection,projection:9}],11,{season:2026}).length,2);
const inventory=inventoryFutureRosterCandidates(gaps,[candidate],[projection])[0].slots[0];
const exclusions=diagnoseFutureReplacementExclusions(gaps,[candidate],[projection],{season:2026,currentWeek:10})[0];
assert.equal(inventory.positionMatches,1);
assert.equal(inventory.uniqueNamePositionTeamWeekCandidates,1);
assert.equal(exclusions.positionCandidates,1);
assert.equal(exclusions.uniqueWeeklyProjection,1);
assert.equal(inventory.verifiedWeekProjectionMatches,0);
assert.equal(inventory.futureAvailabilityVerified,0);
const ambiguous=diagnoseFutureReplacementExclusions(gaps,[candidate],[projection,{...projection,projection:9}],{season:2026,currentWeek:10})[0];
assert.equal(ambiguous.ambiguousWeeklyProjection,1);
const unknown=diagnoseFutureReplacementExclusions(gaps,[{...candidate,byeWeek:null}],[projection],{season:2026,currentWeek:10})[0];
assert.equal(unknown.missingBye,1);
console.log('future-candidate-evidence-tests: all checks passed');
