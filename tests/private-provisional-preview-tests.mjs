import assert from 'node:assert/strict';
import {buildPrivateProvisionalPreview} from '../scripts/build-private-provisional-preview.mjs';
import {renderProvisionalDashboardV1} from '../src/ui/live-dashboard-v1.js';
const estimates=[{week:11,teamName:'<script>alert(1)</script>',slot:'RB',points:7.25,method:'direct-week-ranks-3-to-5'},{week:11,teamName:'Team B',slot:'DEF',points:null,method:'unavailable'}];
const html=buildPrivateProvisionalPreview({week:10,season:2026,provider:'jerrygm',estimates,privateApiKey:'SECRET'});
assert.match(html,/renderProvisionalDashboardV1\(document.getElementById/);
assert.match(html,/\\u003cscript\\u003e/);
assert.doesNotMatch(html,/<script>alert\(1\)<\/script>|SECRET/);
assert.ok(html.includes("connect-src 'none'"));
assert.ok(html.includes("form-action 'none'"));
const root={innerHTML:''};
renderProvisionalDashboardV1(root,{mode:'provisional-evidence',week:10,season:2026,provider:'jerrygm',estimates});
assert.match(root.innerHTML,/1\/2/);
assert.match(root.innerHTML,/7\.3/);
assert.match(root.innerHTML,/Unavailable/);
assert.match(root.innerHTML,/Official playoff probabilities/);
assert.match(root.innerHTML,/&lt;script&gt;/);
assert.doesNotMatch(root.innerHTML,/<script>|playoffProbability|championshipProbability/);
assert.throws(()=>renderProvisionalDashboardV1(root,{mode:'live',estimates}),/Unsupported/);
console.log('private-provisional-preview-tests: all checks passed');
