import assert from 'node:assert/strict';
import {auditYahooScoresWithOverrides} from '../src/data/yahoo-scoring-with-overrides.js';
import {summarizeYahooParticipationCoverage} from '../src/data/yahoo-participation-coverage.js';
const nfl=[{season:2026,week:1,playerId:'n1',name:'James Cook',position:'RB',nflTeam:'BUF',actual:10}];
const yahoo=[{season:2026,week:1,playerId:'y1',name:'James Cook III',position:'RB',nflTeam:'BUF',actual:10},{season:2026,week:2,playerId:'y1',name:'James Cook III',position:'RB',nflTeam:'BUF',actual:0},{season:2026,week:1,playerId:'y2',name:'Unknown Player',position:'WR',nflTeam:'BUF',actual:0},{season:2026,week:1,playerId:'d1',position:'DEF',actual:4}];
const audit=auditYahooScoresWithOverrides(nfl,yahoo);
const report=summarizeYahooParticipationCoverage(nfl,yahoo,audit);
assert.equal(report.summary.matched,1);
assert.equal(report.summary.unresolved,2);
assert.equal(report.summary.unresolvedNonzero,0);
assert.equal(report.summary.categories['known-player-no-same-week-record'],1);
assert.equal(report.summary.categories['identity-not-in-actuals'],1);
assert.equal(report.summary.scoringParityPass,true);
assert.equal(report.summary.participationCoverageComplete,false);
assert.equal(report.summary.excludedDefenses,1);
assert.ok(report.unresolved.every(r=>r.participation==='unverified'));
const nonzero=[...yahoo.slice(0,2),{...yahoo[2],actual:3},yahoo[3]];
const bad=summarizeYahooParticipationCoverage(nfl,nonzero,auditYahooScoresWithOverrides(nfl,nonzero));
assert.equal(bad.summary.scoringParityPass,false);
assert.equal(bad.summary.unresolvedNonzero,1);
console.log('yahoo-participation-coverage-tests: all checks passed');
