import assert from 'node:assert/strict';
import {buildProjectionArchive} from '../src/data/projection-archive.js';
import {evaluatePregameCaptureArchive} from '../src/data/pregame-capture-eligibility.js';
import {importHistoricalProjectionArchives} from '../src/data/historical-projection-importer.js';
const capturedAt='2026-10-13T17:00:00Z',observed='2026-10-13T16:58:00Z',kickoff='2026-10-14T17:00:00Z';
const player={season:2026,week:6,playerId:'p1',name:'Player',position:'RB',projection:14,kickoffAt:kickoff};
const options={capturedAt,provider:'jerrygm',providerByWeek:{6:'jerrygm'},observedAtByWeek:{6:observed}};
const archive=buildProjectionArchive([player],options);
const row=archive.rows[0];
assert.equal(row.forecastProvenance.retrievedAt,observed);
assert.equal(row.forecastProvenance.issuedAt,null);
assert.equal(row.forecastProvenance.issuanceVerified,false);
assert.deepEqual(evaluatePregameCaptureArchive(archive),{rows:1,freshProviderRows:1,pregameKickoffVerifiedRows:1,providerIssuanceVerifiedRows:0,unverifiedRows:0,reasons:{}});
const actuals=[{season:2026,week:6,playerId:'p1',actual:12,actualRecordedAt:'2026-10-15T18:00:00Z'}];
assert.equal(importHistoricalProjectionArchives([{path:'offline.json',data:archive,immutable:true,capturedAt}],actuals).rows.length,1);
const cached=buildProjectionArchive([player],{capturedAt,provider:'cache',providerByWeek:{6:'cache'}});
assert.equal(evaluatePregameCaptureArchive(cached).pregameKickoffVerifiedRows,0);
assert.equal(evaluatePregameCaptureArchive(cached).reasons['unverified-retrieval'],1);
const late=buildProjectionArchive([{...player,kickoffAt:'2026-10-13T16:59:00Z'}],options);
assert.equal(evaluatePregameCaptureArchive(late).pregameKickoffVerifiedRows,0);
assert.equal(evaluatePregameCaptureArchive(late).reasons['kickoff-not-verified-pregame'],1);
const unknown=buildProjectionArchive([{...player,kickoffAt:undefined}],options);
assert.equal(evaluatePregameCaptureArchive(unknown).pregameKickoffVerifiedRows,0);
