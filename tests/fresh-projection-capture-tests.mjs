import assert from 'node:assert/strict';
import {captureFreshProjectionArchive} from '../src/data/fresh-projection-capture.js';
const spec={season:2026,week:6,sourceAudit:{leagueKey:'470.l.244897'}};
const player={season:2026,week:6,playerId:'p1',name:'Test Player',position:'QB',projection:12};
let saved=0;
const save=()=>{saved++;return 'test.json';};
const observedAt=new Date(Date.now()-1000).toISOString();
const live=async()=>({provider:'jerrygm',rows:[player],trust:{weekResults:[{week:6,provider:'jerrygm',observedAt}]}});
const result=await captureFreshProjectionArchive({spec,load:live,save});
assert.equal(result.freshProviderRows,1);
const cache=async()=>({provider:'cache',rows:[player],trust:{weekResults:[{week:6,provider:'cache',observedAt:null}]}});
await assert.rejects(captureFreshProjectionArchive({spec,load:cache,save}),/No fresh provider observations/);
assert.equal(saved,1);
console.log('fresh-projection-capture-tests: all checks passed');
