import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
execFileSync(process.execPath,['scripts/generate-e2e-fixture-projections.mjs'],{stdio:'pipe'});
const env={...process.env,FANTASYPROS_API_KEY:''};
const output=execFileSync(process.execPath,['scripts/run-weekly-intelligence.mjs','fixtures/prepared-league.json','fixtures/weekly-intelligence-spec.json'],{encoding:'utf8',env});
assert.match(output,/WEEKLY INTELLIGENCE: Alpha — Week 11/);
assert.match(output,/Record 7-3 \| Seed #1 \| Playoffs/);
assert.match(output,/Matchup vs Delta: win/);
assert.match(output,/Data: fixture .*trust PASS/);
assert.match(output,/Starting lineup: 5 players/);
assert.doesNotMatch(output,/"readiness"/,'default output should remain concise');
const spec=JSON.parse(fs.readFileSync('fixtures/weekly-intelligence-spec.json','utf8'));
const jsonSpecPath='data/private/weekly-intelligence-command-test-spec.json';
fs.mkdirSync('data/private',{recursive:true});
fs.writeFileSync(jsonSpecPath,JSON.stringify({...spec,includeJson:true}));
const jsonOutput=execFileSync(process.execPath,['scripts/run-weekly-intelligence.mjs','fixtures/prepared-league.json',jsonSpecPath],{encoding:'utf8',env});
const jsonStart=jsonOutput.indexOf('{\n  "readiness"');
assert.ok(jsonStart>=0,'expected JSON payload when includeJson=true');
const payload=JSON.parse(jsonOutput.slice(jsonStart));
assert.equal(payload.readiness.ready,true);
assert.equal(payload.report.team.id,'T1');
assert.equal(payload.report.matchup.week,11);
assert.equal(payload.report.trust.projections.provider,'fixture');
assert.equal(payload.report.trust.projections.degraded,false);
fs.rmSync(jsonSpecPath,{force:true});
console.log('weekly-intelligence-command-tests: all checks passed');
